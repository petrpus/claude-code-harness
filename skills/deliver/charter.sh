#!/usr/bin/env bash
# skills/deliver/charter.sh — build an autopilot charter (PROMPT.md, shaped
# like skills/autopilot/PROMPT.template.md) from one GitHub issue and its Map.
# Pure: issue JSON and the extracted Delivery plan in, Markdown out. Needs jq
# and map.sh (for map_line_title).
#
# The charter is what the verifier checks "done" against, so the issue's own
# acceptance criteria go in verbatim, and every other issue in the Map is
# named as out of scope — the neighbours are the likeliest scope creep.

# _md_section <heading> — stdin body, prints the lines under "## <heading>"
# up to the next "## " heading. CR stripped.
_md_section() {
  tr -d '\r' | awk -v h="$1" '
    $0 ~ ("^##[[:space:]]+" h "[[:space:]]*$") { inside=1; next }
    /^##[[:space:]]/ { inside=0 }
    inside { print }'
}

# _trim_blank — drop leading and trailing blank lines from stdin.
_trim_blank() {
  awk '{ lines[NR]=$0 } END {
    s=1; while (s<=NR && lines[s] ~ /^[[:space:]]*$/) s++
    e=NR; while (e>=s && lines[e] ~ /^[[:space:]]*$/) e--
    for (i=s; i<=e; i++) print lines[i] }'
}

# issue_flags — stdin issue body, prints one "<name>\t<off|on>" line per
# declared flag (#132). A declaration is a line of its own,
# `Flag: <NAME> (default off|on)`; the key is case-insensitive and the
# default is off when the parenthesis is missing. A line inside a ``` or ~~~
# fenced block is a quoted example, not a declaration, and a name declared
# twice keeps its first declaration. The verifier treats a declared flag as
# spec, not as shortcut 8 — a wrong match loosens the gate, so stay strict.
issue_flags() {
  tr -d '\r' | awk '
    /^[[:space:]]*(```|~~~)/ { fenced = !fenced; next }
    fenced { next }
    {
      line = $0
      if (tolower(line) !~ /^[[:space:]]*flag:[[:space:]]*[a-z0-9_.-]+/) next
      sub(/^[[:space:]]*[Ff][Ll][Aa][Gg]:[[:space:]]*/, "", line)
      name = line; sub(/[^A-Za-z0-9_.-].*$/, "", name)
      if (name in seen) next
      seen[name] = 1
      def = (tolower(line) ~ /\([[:space:]]*default[[:space:]]+on[[:space:]]*\)/) ? "on" : "off"
      print name "\t" def
    }'
}

# charter_from_issue <issue_json_file> <map_plan_file> <map_number>
charter_from_issue() {
  local issue="$1" plan="$2" map="$3"
  local n title url body goal ac line id other_title
  n="$(jq -r '.number' "$issue")"
  title="$(jq -r '.title' "$issue")"
  url="$(jq -r '.url // empty' "$issue")"
  body="$(jq -r '.body // ""' "$issue")"

  goal="$(printf '%s\n' "$body" | _md_section 'What to build' | _trim_blank)"
  [[ -n "$goal" ]] || goal="Implement issue #$n as described in the issue body below."
  ac="$(printf '%s\n' "$body" | _md_section 'Acceptance criteria' | grep -E '^[[:space:]]*[-*][[:space:]]+\[[ xX]\]' || true)"
  [[ -n "$ac" ]] || ac="- [ ] Issue #$n is implemented as its body below describes."

  cat <<EOF
# Autopilot charter — issue #$n: $title

<!-- Generated by /deliver (skills/deliver/charter.sh) from issue #$n and map #$map. Immutable for this run. -->

## Source

- Issue: ${url:-#$n}
- Map: #$map (this issue is one entry of its Delivery section)

## Goal

$goal

## Acceptance criteria

$ac
- [ ] All acceptance tests pass under the project verify command.

## In scope

- Only what issue #$n describes. It lands as one reviewed PR.

## Out of scope

EOF
  local others=0
  while IFS= read -r line; do
    id="$(plan_parse_line "$line" | cut -f1)" || continue
    [[ "$id" == "#$n" || -z "$id" ]] && continue
    other_title="$(map_line_title "$line")"
    printf -- '- %s%s — delivered by its own issue and PR; do not implement it here.\n' \
      "$id" "${other_title:+ $other_title}"
    others=1
  done < "$plan"
  [[ "$others" -eq 1 ]] || echo "- Anything not described by issue #$n."

  local flags flag_note=""
  flags="$(printf '%s\n' "$body" | issue_flags)"
  if [[ -n "$flags" ]]; then
    printf '\n## Declared flags\n\n'
    printf '%s\n' "$flags" | awk -F'\t' '{ printf "- Flag: %s (default %s)\n", $1, $2 }'
    flag_note=$'\n- A flag under "Declared flags" is part of the spec: ship the change behind it\n  with the declared default, and test the new path with the flag forced on.'
  fi

  cat <<EOF

## Constraints & notes

- Follow the repo's \`CLAUDE.md\` (or \`.claude/CLAUDE.md\`) and \`CONTEXT.md\`.
- Tests are required for every behavior change (TDD: red-green-refactor).
- Record any architectural decision as a \`docs/adr/\` entry.
- Do not open, push or merge anything — the /deliver runner does that (ADR-0007).$flag_note

## Issue #$n (verbatim)

$(printf '%s\n' "$body" | tr -d '\r' | _trim_blank)
EOF
}
